import fs from "node:fs/promises"
import path from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const changelogPath = path.join(rootDir, "src", "data", "changelog.ts")
const outputPath = path.join(rootDir, "src", "generated", "recent-changes.ts")

const MAX_ITEMS = 8
const LOG_COUNT = 30
const FALLBACK_COUNT = 20
const ALLOWED_TYPES = new Map([
  ["feat", "feature"],
  ["fix", "fix"],
  ["perf", "perf"],
])

const SUBJECT_RE = /^(feat|fix|perf)(\(.+?\))?(!)?:\s*(.+?)\s*$/

async function getCuratedDate() {
  try {
    const raw = await fs.readFile(changelogPath, "utf-8")
    const m = raw.match(/date:\s*"(\d{4}-\d{2}-\d{2})"/)
    return m ? m[1] : null
  } catch {
    return null
  }
}

function gitLog() {
  const raw = execFileSync(
    "git",
    ["log", `-n`, String(LOG_COUNT), "--pretty=format:%H|%ad|%s", "--date=short", "--no-merges"],
    { cwd: rootDir, encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] }
  )
  return raw
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      const sep1 = line.indexOf("|")
      const sep2 = line.indexOf("|", sep1 + 1)
      if (sep1 === -1 || sep2 === -1) return null
      return {
        sha: line.slice(0, sep1),
        date: line.slice(sep1 + 1, sep2),
        subject: line.slice(sep2 + 1),
      }
    })
    .filter((e) => e !== null)
}

function toItem(entry) {
  if (entry.subject.startsWith("Merge ")) return null
  const m = SUBJECT_RE.exec(entry.subject)
  if (!m) return null
  const type = ALLOWED_TYPES.get(m[1])
  if (!type) return null
  const text = (m[4] || "").trim()
  if (!text) return null
  return {
    type,
    text,
    sha: entry.sha.slice(0, 7),
    date: /^\d{4}-\d{2}-\d{2}$/.test(entry.date) ? entry.date : "",
  }
}

function render(items) {
  const lines = [
    "// AUTO-GENERATED by scripts/write-recent-changes.mjs — do not edit manually.",
    "// Ultimi commit convenzionali user-visibili (feat/fix/perf) più nuovi della",
    "// voce curata in testa a src/data/changelog.ts. Rigenera con gli hook",
    "// predev/prebuild/pretest o con lo step dedicato in .github/workflows/docker.yml.",
    "// Senza git il file esistente resta intatto (il builder Docker non ha .git).",
    "export interface RecentChange {",
    '  type: "feature" | "perf" | "fix"',
    "  text: string",
    "  sha: string",
    "  date: string",
    "}",
    "",
    "export const RECENT_CHANGES: RecentChange[] = [",
  ]
  for (const it of items) {
    lines.push(
      `  { type: ${JSON.stringify(it.type)}, text: ${JSON.stringify(it.text)}, sha: ${JSON.stringify(it.sha)}, date: ${JSON.stringify(it.date)} },`
    )
  }
  lines.push("]", "")
  return lines.join("\n")
}

async function main() {
  let entries = []
  try {
    entries = gitLog()
  } catch {
    // Senza git (builder Docker): mai rompere la build e mai azzerare il file
    // buono arrivato col context CI — esci lasciando tutto com'è.
    console.log("[recent-changes] git non disponibile: file esistente invariato")
    return
  }
  if (entries.length === 0) {
    console.log("[recent-changes] nessuno storico git: file esistente invariato")
    return
  }
  const curatedDate = await getCuratedDate()
  let pool = entries
  if (curatedDate) {
    const newer = entries.filter((e) => e.date > curatedDate)
    // Solo commit davvero nuovi; se la curata copre già tutto, niente auto.
    pool = newer.length > 0 ? newer : []
  } else {
    pool = entries.slice(0, FALLBACK_COUNT)
  }
  const items = []
  for (const e of pool) {
    if (items.length >= MAX_ITEMS) break
    const it = toItem(e)
    if (it) items.push(it)
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, render(items))
  console.log(`[recent-changes] ${items.length} voci da ${entries.length} commit (curata: ${curatedDate ?? "sconosciuta"})`)
}

// Top-level await come write-app-version.mjs; errori imprevisti fuori dal
// blocco git non devono mai rompere predev/prebuild/pretest.
try {
  await main()
} catch (e) {
  console.warn(`[recent-changes] generazione saltata: ${e instanceof Error ? e.message : String(e)}`)
}
